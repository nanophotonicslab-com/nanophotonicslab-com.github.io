/** Map a normalized value t ∈ [0,1] to an RGB triplet via viridis. */
export function viridis(t: number): [number, number, number] {
  const n = VIRIDIS_DATA.length;
  const i = Math.max(0, Math.min(n - 1, Math.floor(t * (n - 1))));
  return VIRIDIS_DATA[i];
}

/** Draw a vertical colorbar on a canvas element. */
export function drawColorbar(
  canvas: HTMLCanvasElement,
  min: number,
  max: number,
  label: string,
): void {
  const ctx = canvas.getContext('2d')!;
  const w = canvas.width;
  const h = canvas.height;
  const barW = 20;
  const barX = 10;
  const barTop = 30;
  const barBot = h - 30;
  const barH = barBot - barTop;

  ctx.clearRect(0, 0, w, h);

  // Draw color gradient
  for (let y = 0; y < barH; y++) {
    const t = 1 - y / barH;  // top = max, bottom = min
    const [r, g, b] = viridis(t);
    ctx.fillStyle = `rgb(${r * 255},${g * 255},${b * 255})`;
    ctx.fillRect(barX, barTop + y, barW, 1);
  }

  const ct = chartTheme();

  // Border
  ctx.strokeStyle = ct.textSoft;
  ctx.strokeRect(barX, barTop, barW, barH);

  // Labels
  ctx.fillStyle = ct.text;
  ctx.font = '11px Inter, system-ui';
  ctx.textAlign = 'left';
  ctx.fillText(max.toFixed(1), barX + barW + 5, barTop + 5);
  ctx.fillText(min.toFixed(1), barX + barW + 5, barBot + 3);

  // Title
  ctx.textAlign = 'center';
  ctx.fillText(label, barX + barW / 2, 15);
}
